class Fandom {
  final int id;
  final String title;
  final String category;
  final String depth;
  final String badge;
  final String img;
  final String summary;
  final String fullBody;

  Fandom({
    required this.id,
    required this.title,
    required this.category,
    required this.depth,
    required this.badge,
    required this.img,
    required this.summary,
    required this.fullBody,
  });
}